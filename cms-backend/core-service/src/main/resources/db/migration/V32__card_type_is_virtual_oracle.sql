-- V32: Virtual card type flag + digital (app-only) production status.
-- Virtual cards are issued in CMS for the app; they never go to bureau/print.

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE CARD_TYPE ADD IS_VIRTUAL NUMBER(1) DEFAULT 0';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

UPDATE CARD_TYPE SET IS_VIRTUAL = 0 WHERE IS_VIRTUAL IS NULL;

-- 003 = Digital Issued (app-only / virtual — not for bureau export)
BEGIN
  INSERT INTO CARD_PRODUCTION_STATUS (
      CARD_PROD_STATUS_ID, CARD_PROD_STATUS_NAME, CREATED_ON, CREATED_BY, UPDATED_ON, UPDATED_BY)
  SELECT '003', 'Digital Issued', SYSTIMESTAMP, 'system', SYSTIMESTAMP, 'system'
  FROM DUAL
  WHERE NOT EXISTS (
      SELECT 1 FROM CARD_PRODUCTION_STATUS WHERE CARD_PROD_STATUS_ID = '003');
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE NOT IN (-1, -942) THEN RAISE; END IF;
END;
/

COMMIT;
