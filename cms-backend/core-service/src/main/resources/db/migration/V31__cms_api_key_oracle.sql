-- V31: Channel API keys for cms-app (single active key model) + Security menu

BEGIN EXECUTE IMMEDIATE 'CREATE TABLE CMS_API_KEY (
    ID NUMBER(19) NOT NULL PRIMARY KEY,
    KEY_PREFIX VARCHAR2(32) NOT NULL,
    KEY_HASH VARCHAR2(128) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_BY VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    REVOKED_BY VARCHAR2(50),
    REVOKED_AT TIMESTAMP,
    LAST_USED_AT TIMESTAMP
)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE CMS_API_KEY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_CMS_API_KEY_STATUS ON CMS_API_KEY (STATUS)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_CMS_API_KEY_HASH ON CMS_API_KEY (KEY_HASH)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

INSERT INTO CMS_MENU (ID, MENU_NAME, MENU_PATH, MENU_ICON, SORT_ORDER, STATUS)
SELECT CMS_MENU_SEQ.NEXTVAL, 'API Keys', '/security/api-keys', 'pi-key', 22, 'Y'
FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM CMS_MENU WHERE MENU_PATH = '/security/api-keys');

INSERT INTO CMS_ROLE_MENU (ID, ROLE_CODE, MENU_ID, CREATED_AT)
SELECT CMS_ROLE_MENU_SEQ.NEXTVAL, 'ADMIN', m.ID, SYSTIMESTAMP
FROM CMS_MENU m
WHERE m.MENU_PATH = '/security/api-keys'
  AND NOT EXISTS (
    SELECT 1 FROM CMS_ROLE_MENU rm
    WHERE rm.ROLE_CODE = 'ADMIN' AND rm.MENU_ID = m.ID
  );

COMMIT;
