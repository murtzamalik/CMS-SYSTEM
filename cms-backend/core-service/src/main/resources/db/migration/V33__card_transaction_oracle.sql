-- V33: Per-authorize transaction journal for history / statement APIs.

BEGIN
  EXECUTE IMMEDIATE 'CREATE SEQUENCE CARD_TRANSACTION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE CARD_TRANSACTION (
      ID                NUMBER(19)      NOT NULL,
      PAN               VARCHAR2(50)    NOT NULL,
      PAN_HASH          VARCHAR2(128),
      RELATIONSHIP_NUM  VARCHAR2(50),
      AMOUNT            NUMBER(17,3)    NOT NULL,
      CHANNEL_CODE      VARCHAR2(30)    NOT NULL,
      TRAN_CODE         VARCHAR2(30)    NOT NULL,
      RESPONSE_CODE     NUMBER(10)      NOT NULL,
      RESPONSE_MESSAGE  VARCHAR2(255),
      AVAILABLE_AFTER   NUMBER(17,3),
      AUTH_REF          VARCHAR2(100),
      CREATED_ON        TIMESTAMP       NOT NULL,
      CREATED_BY        VARCHAR2(50)    NOT NULL,
      CONSTRAINT PK_CARD_TRANSACTION PRIMARY KEY (ID)
    )';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_CARD_TXN_REL_CREATED ON CARD_TRANSACTION (RELATIONSHIP_NUM, CREATED_ON DESC)';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_CARD_TXN_PAN_CREATED ON CARD_TRANSACTION (PAN, CREATED_ON DESC)';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMIT;
