BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE CARD (
    CARD_ID NUMBER(19) NOT NULL PRIMARY KEY,
    PAN VARCHAR2(50),
    RELATIONSHIP_NUM VARCHAR2(50),
    CARD_TITLE VARCHAR2(255),
    EXPIRY_DATE TIMESTAMP,
    CARD_TYPE_CODE VARCHAR2(50),
    LIMIT_PROFILE VARCHAR2(50),
    SUPPLEMENTARY_COUNT NUMBER(10),
    CARD_STATUS_CODE VARCHAR2(50),
    PRIMARY_CARD_NUM VARCHAR2(50),
    ACTIVATION_DATE TIMESTAMP,
    PRODUCT_CODE VARCHAR2(50),
    ISSUED_DATE TIMESTAMP,
    BRANCH_CODE VARCHAR2(50),
    CARD_PROD_STATUS_ID VARCHAR2(50),
    WHEN_DELETED TIMESTAMP,
    IS_REPLACED NUMBER(1) DEFAULT 0,
    CREATED_ON TIMESTAMP,
    CREATED_BY VARCHAR2(50),
    UPDATED_ON TIMESTAMP,
    UPDATED_BY VARCHAR2(50),
    REQUEST_TYPE VARCHAR2(50),
    TRIM_PAN VARCHAR2(50),
    IS_MAKER NUMBER(1),
    TO_CARD_STATUS_CODE VARCHAR2(50),
    ECOMMERCE_ALLOWED VARCHAR2(10),
    CVV VARCHAR2(20),
    CVV2 VARCHAR2(20),
    ICVV VARCHAR2(20),
    TRACK1_DATA VARCHAR2(500),
    TRACK2_DATA VARCHAR2(500),
    TO_CARD_TITLE VARCHAR2(255),
    TO_CARD_TYPE_CODE VARCHAR2(50),
    TO_DEBIT_PROD_CODE VARCHAR2(50),
    OPERATION_TYPE VARCHAR2(50),
    CONSTRAINT UK_CARD_PAN UNIQUE (PAN),
    CONSTRAINT FK_CARD_BRANCH FOREIGN KEY (BRANCH_CODE) REFERENCES BRANCH(BRANCH_CODE),
    CONSTRAINT FK_CARD_STATUS FOREIGN KEY (CARD_STATUS_CODE) REFERENCES CARD_STATUS(CARD_STATUS_CODE),
    CONSTRAINT FK_CARD_PROD_STATUS FOREIGN KEY (CARD_PROD_STATUS_ID) REFERENCES CARD_PRODUCTION_STATUS(CARD_PROD_STATUS_ID)
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

