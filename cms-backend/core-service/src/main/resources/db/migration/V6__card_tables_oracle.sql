BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE CARD_TYPE (
    CARD_TYPE_CODE VARCHAR2(50) NOT NULL PRIMARY KEY,
    IS_SUPP_TYPE NUMBER(1),
    SUPP_TYPE_CODE VARCHAR2(50),
