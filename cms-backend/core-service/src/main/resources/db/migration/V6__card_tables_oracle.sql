BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE CARD_ACCOUNT (
    PAN VARCHAR2(50) NOT NULL,
    ACCOUNT_NUM VARCHAR2(50) NOT NULL,
    EFFECTIVE_FROM TIMESTAMP,
    RELATIONSHIP_NUM VARCHAR2(50),
    EFFECTIVE_TO TIMESTAMP,
    IS_OVERALL_DEFAULT NUMBER(1) DEFAULT 0,
    IS_ACCT_TYPE_DEFAULT NUMBER(1) DEFAULT 0,
    CREATED_ON TIMESTAMP,
    CREATED_BY VARCHAR2(50),
    UPDATED_ON TIMESTAMP,
    UPDATED_BY VARCHAR2(50),
    PRIMARY KEY (PAN, ACCOUNT_NUM),
    CONSTRAINT FK_CARD_ACCT_CARD FOREIGN KEY (PAN) REFERENCES CARD(PAN),
    CONSTRAINT FK_CARD_ACCT_ACCOUNT FOREIGN KEY (ACCOUNT_NUM) REFERENCES ACCOUNT(ACCOUNT_NUM)
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

